// https://github.com/yoksel/url-encoder/blob/master/src/js/script.js#L46
function encodeSvg(svg: string) {
  const namespaced = addNameSpace(svg);
  const escaped = encodeSVG(namespaced);

  return escaped;
}

const symbols = /[\r\n%#()<>?[\\\]^`{|}]/g;

const externalQuotesValue: 'single' | 'double' = 'double';
const double = `"`;
const single = `'`;
const quotes = {
  level1: externalQuotesValue === 'double' ? double : single,
  level2: externalQuotesValue === 'double' ? single : double,
};

function addNameSpace(data: string) {
  if (data.indexOf('http://www.w3.org/2000/svg') < 0) {
    return data.replace(/<svg/g, `<svg xmlns=${quotes.level2}http://www.w3.org/2000/svg${quotes.level2}`);
  }

  return data;
}

function encodeSVG(svg: string) {
  let data = svg;
  // Use single quotes instead of double to avoid encoding.
  if (externalQuotesValue === 'double') {
    data = data.replace(/"/g, `'`);
  } else {
    data = data.replace(/'/g, `"`);
  }

  data = data.replace(/>\s{1,}</g, '><');
  data = data.replace(/\s{2,}/g, ' ');

  // Using encodeURIComponent() as replacement function
  // allows to keep result code readable
  return data.replace(symbols, encodeURIComponent);
}
