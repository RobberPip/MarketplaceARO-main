export const buildIcons = (): PluginOption => {
  const logger = createLogger();
  return {
    name: 'build-icons',
    enforce: 'pre',

    buildStart() {
      try {
        const vars = [];
        const classes = [];

        // Tabler Icons
        for (const name of tablerIcons) {
          const icon = icons[name];

          let iconName = name;
          let iconPath = path.resolve(__dirname, '..', 'node_modules/@tabler/icons/icons');

          if ('outline' in icon.styles) {
            iconPath = path.join(iconPath, 'outline', `${iconName}.svg`);
          } else if ('filled' in icon.styles) {
            iconName += '-filled';
            iconPath = path.join(iconPath, 'filled', `${iconName}.svg`);
          }

          if (!fs.existsSync(iconPath)) {
            throw new Error(`Icon doesn't exists: ${iconPath}`);
          }

          let svgContent = fs.readFileSync(iconPath, 'utf-8');

          // svgContent = svgContent.replace('stroke-width="2"', 'stroke-width="1"');
          svgContent = svgContent.replace(/class="[^"]*"/, '');

          const encodedSvg = encodeSvg(svgContent);

          vars.push(`--icon-${iconName}: url("data:image/svg+xml,${encodedSvg}");`);
          classes.push(iconClass(iconName));
        }

        // Custom Icons
        const svgDir = path.resolve(__dirname, '..', 'frontend/shared/assets/icons');

        if (fs.existsSync(svgDir)) {
          const svgFiles = fs.readdirSync(svgDir).filter((file) => file.endsWith('.svg'));

          for (const file of svgFiles) {
            const iconName = path.basename(file, '.svg');

            if (icons[iconName]) {
              throw new Error('Icon aleady exists!');
            }

            const svgContent = fs.readFileSync(path.join(svgDir, file), 'utf-8');
            const encodedSvg = encodeSvg(svgContent);

            vars.push(`--icon-${iconName}: url("data:image/svg+xml,${encodedSvg}");`);
            classes.push(iconClass(iconName));
          }
        }

        // save icons.css
        fs.writeFileSync(
          path.resolve(__dirname, '..', 'frontend/shared/assets/icons.css'),
          iconsCss({ classes: classes, vars: vars }),
          'utf-8',
        );
        logger.info('SVG icons CSS generated!', { timestamp: true });
      } catch (e) {
        logger.error(`SVG icons generation failed: ${e}`, { timestamp: true });
      }
    },
  };
};

